package margematenta.persistencia;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import margematenta.dominio.Alerta;
import margematenta.dominio.NivelAlerta;
import margematenta.dominio.TipoSensor;

public class AlertaDAO {

    public void criarTabela() throws SQLException {
        String sql = """
                CREATE TABLE IF NOT EXISTS alertas (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tipo VARCHAR(32) NOT NULL,
                    nivel VARCHAR(16) NOT NULL,
                    valor_previsto DOUBLE PRECISION NOT NULL,
                    limiar_atingido DOUBLE PRECISION NOT NULL,
                    estrategia VARCHAR(80) NOT NULL,
                    data_hora TIMESTAMP WITH TIME ZONE NOT NULL
                )
                """;

        try (Connection conexao = BancoDados.abrirConexao();
             PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.executeUpdate();
        }
    }

    public void salvar(Alerta alerta) throws SQLException {
        String sql = """
                INSERT INTO alertas (
                    tipo, nivel, valor_previsto, limiar_atingido, estrategia, data_hora
                )
                VALUES (?, ?, ?, ?, ?, ?)
                """;

        try (Connection conexao = BancoDados.abrirConexao();
             PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.setString(1, alerta.tipo().name());
            comando.setString(2, alerta.nivel().name());
            comando.setDouble(3, alerta.valorPrevisto());
            comando.setDouble(4, alerta.limiarAtingido());
            comando.setString(5, alerta.estrategia());
            comando.setObject(6, alerta.dataHora().atOffset(ZoneOffset.UTC));
            comando.executeUpdate();
        }
    }

    public List<Alerta> listarTodos() throws SQLException {
        String sql = """
                SELECT tipo, nivel, valor_previsto, limiar_atingido, estrategia, data_hora
                FROM alertas
                ORDER BY data_hora DESC, id DESC
                """;

        List<Alerta> alertas = new ArrayList<>();

        try (Connection conexao = BancoDados.abrirConexao();
             PreparedStatement comando = conexao.prepareStatement(sql);
             ResultSet resultado = comando.executeQuery()) {
            while (resultado.next()) {
                OffsetDateTime dataHora =
                        resultado.getObject("data_hora", OffsetDateTime.class);

                alertas.add(new Alerta(
                        TipoSensor.valueOf(resultado.getString("tipo")),
                        NivelAlerta.valueOf(resultado.getString("nivel")),
                        resultado.getDouble("valor_previsto"),
                        resultado.getDouble("limiar_atingido"),
                        resultado.getString("estrategia"),
                        dataHora.toInstant()
                ));
            }
        }

        return alertas;
    }
}