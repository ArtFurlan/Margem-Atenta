package margematenta.persistencia;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import margematenta.dominio.Medicao;
import margematenta.dominio.TipoSensor;

public class MedicaoDAO {

    public void criarTabela() throws SQLException {
        String sql = """
                CREATE TABLE IF NOT EXISTS medicoes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tipo VARCHAR(32) NOT NULL,
                    valor DOUBLE PRECISION NOT NULL,
                    data_hora TIMESTAMP WITH TIME ZONE NOT NULL
                )
                """;

        try (Connection conexao = BancoDados.abrirConexao();
             PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.executeUpdate();
        }
    }

    public void salvar(Medicao medicao) throws SQLException {
        String sql = """
                INSERT INTO medicoes (tipo, valor, data_hora)
                VALUES (?, ?, ?)
                """;

        try (Connection conexao = BancoDados.abrirConexao();
             PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.setString(1, medicao.tipo().name());
            comando.setDouble(2, medicao.valor());
            comando.setObject(3, medicao.dataHora().atOffset(ZoneOffset.UTC));
            comando.executeUpdate();
        }
    }

    public List<Medicao> buscarHistoricoPorSensor(TipoSensor tipo) throws SQLException {
        String sql = """
                SELECT valor, data_hora
                FROM medicoes
                WHERE tipo = ?
                ORDER BY data_hora DESC, id DESC
                """;

        List<Medicao> historico = new ArrayList<>();

        try (Connection conexao = BancoDados.abrirConexao();
             PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.setString(1, tipo.name());

            try (ResultSet resultado = comando.executeQuery()) {
                while (resultado.next()) {
                    double valor = resultado.getDouble("valor");
                    OffsetDateTime dataHora =
                            resultado.getObject("data_hora", OffsetDateTime.class);

                    historico.add(new Medicao(tipo, valor, dataHora.toInstant()));
                }
            }
        }

        return historico;
    }
}